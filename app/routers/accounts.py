"""Account endpoints: create account, read account, read balance, transaction history."""

from __future__ import annotations

from typing import Annotated

from fastapi import APIRouter, Path, Query, status

from app import schemas
from app.dependencies import AppSettings, DbSession
from app.models import TransactionType
from app.routers.common import ERROR_RESPONSES, validation_error
from app.services import ledger

router = APIRouter(prefix="/accounts", tags=["Accounts"])

AccountIdPath = Annotated[str, Path(description="Account identifier (UUID).", min_length=1)]


@router.post(
    "",
    status_code=status.HTTP_201_CREATED,
    response_model=schemas.AccountResponse,
    summary="Create an account",
    description=(
        "Creates a new account for the given holder name. The balance always starts at **0.00** and "
        "`id` / `created_at` are generated by the server. Any attempt to supply a `balance` (or any "
        "other unknown field) is rejected with a `VALIDATION_ERROR`."
    ),
    responses={400: ERROR_RESPONSES[400]},
)
def create_account(payload: schemas.AccountCreate, db: DbSession) -> schemas.AccountResponse:
    account = ledger.create_account(db, payload)
    return ledger.account_to_schema(account)


@router.get(
    "/{account_id}",
    response_model=schemas.AccountResponse,
    summary="Get an account",
    responses={404: ERROR_RESPONSES[404]},
)
def get_account(account_id: AccountIdPath, db: DbSession) -> schemas.AccountResponse:
    return ledger.account_to_schema(ledger.get_account(db, account_id))


@router.get(
    "/{account_id}/balance",
    response_model=schemas.BalanceResponse,
    summary="Get account balance",
    description="Returns the current balance of the account.",
    responses={404: ERROR_RESPONSES[404]},
)
def get_balance(account_id: AccountIdPath, db: DbSession) -> schemas.BalanceResponse:
    account = ledger.get_account(db, account_id)
    return schemas.BalanceResponse(
        account_id=account.id,
        name=account.name,
        balance=ledger.format_money(account.balance_minor),
    )


@router.post(
    "/{account_id}/transactions",
    status_code=status.HTTP_201_CREATED,
    response_model=schemas.TransactionCreatedResponse,
    summary="Add a transaction to an account",
    description=(
        "Posts a `credit` or `debit` transaction and updates the account balance in the **same database "
        "transaction**.\n\n"
        "* A debit that exceeds the current balance is rejected (`422 INSUFFICIENT_BALANCE`) and the balance "
        "is left untouched.\n"
        "* `reference_id` must be unique per account. Re-submitting the same `reference_id` returns "
        "`409 DUPLICATE_TRANSACTION` with the original transaction in `details.existing_transaction`; nothing "
        "new is created and the balance does not change.\n"
        "* Transactions are immutable: there is no update or delete endpoint."
    ),
    responses={
        400: ERROR_RESPONSES[400],
        404: ERROR_RESPONSES[404],
        409: ERROR_RESPONSES[409],
        422: ERROR_RESPONSES[422],
    },
)
def add_transaction(
    account_id: AccountIdPath, payload: schemas.TransactionCreate, db: DbSession
) -> schemas.TransactionCreatedResponse:
    posted = ledger.post_transaction(db, account_id, payload)
    base = ledger.transaction_to_schema(posted.transaction)
    return schemas.TransactionCreatedResponse(
        **base.model_dump(), balance_after=ledger.format_money(posted.balance_after_minor)
    )


@router.get(
    "/{account_id}/transactions",
    response_model=schemas.TransactionListResponse,
    summary="Get transaction history",
    description=(
        "Returns the account's transactions in **latest-first** order (by `created_at`).\n\n"
        "* Filter with `type=credit` or `type=debit`; omit it to get both.\n"
        "* Paginate with `page` (1-based) and `limit`. The `pagination` object tells the client the current "
        "page, page size, total records and total pages."
    ),
    responses={400: ERROR_RESPONSES[400], 404: ERROR_RESPONSES[404]},
)
def list_transactions(
    account_id: AccountIdPath,
    db: DbSession,
    settings: AppSettings,
    type: Annotated[
        TransactionType | None,
        Query(description="Filter by transaction type. Omit to return both credits and debits."),
    ] = None,
    page: Annotated[int, Query(ge=1, description="Page number (1-based).")] = 1,
    limit: Annotated[int | None, Query(ge=1, description="Page size (1-100). Defaults to 20.")] = None,
) -> schemas.TransactionListResponse:
    page_size = limit if limit is not None else settings.default_page_size
    if page_size > settings.max_page_size:
        raise validation_error(f"limit must be between 1 and {settings.max_page_size}.", field="query.limit")
    result = ledger.list_transactions(db, account_id, txn_type=type, page=page, limit=page_size)
    return result.to_schema()
